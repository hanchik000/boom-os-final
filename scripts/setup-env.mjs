// Prepares the .env this project refuses to start without.
//
// server/config.ts stops the process when DATABASE_URL or JWT_SECRET is missing, and
// docker-compose.yml refuses to start without POSTGRES_PASSWORD and JWT_SECRET. The file is
// deliberately not in the repository (it holds passwords), so a fresh clone cannot start until
// someone writes one by hand -- that is the step people lose time on.
//
// This script writes it once, with real random secrets, and is safe to run again: it never
// overwrites a value that is already set, it only fills in what is missing.
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const ENV_PATH = path.join(process.cwd(), '.env');
const secret = (bytes = 24) => randomBytes(bytes).toString('base64url'); // URL-safe: also valid inside DATABASE_URL

const existing = new Map();
if (fs.existsSync(ENV_PATH)) {
  for (const line of fs.readFileSync(ENV_PATH, 'utf8').split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
    if (m && m[2].trim()) existing.set(m[1], m[2].trim());
  }
}

const dbUser = existing.get('POSTGRES_USER') || 'boom_admin';
const dbName = existing.get('POSTGRES_DB') || 'boom_os';
const dbPassword = existing.get('POSTGRES_PASSWORD') || secret();
const ownerPassword = existing.get('BOOTSTRAP_OWNER_PASSWORD') || secret(12);

const defaults = {
  POSTGRES_DB: dbName,
  POSTGRES_USER: dbUser,
  POSTGRES_PASSWORD: dbPassword,
  JWT_SECRET: secret(32),
  // Used when the server runs on this machine (npm run dev / npm start). Inside docker compose
  // the api service sets its own DATABASE_URL pointing at the postgres container, so one .env
  // serves both ways of running.
  DATABASE_URL: `postgresql://${dbUser}:${dbPassword}@localhost:5432/${dbName}?schema=public`,
  HOST: '127.0.0.1',
  PORT: '3000',
  BOOM_OS_PORT: '3000',
  NODE_ENV: 'development',
  DEFAULT_TIMEZONE: 'Asia/Ashgabat',
  DEFAULT_CURRENCY: 'TMT',
  APP_URL: 'http://localhost:3000',
  // The first OWNER, created once on an empty database. The password must be at least 12
  // characters or the server stops with a configuration error.
  BOOTSTRAP_OWNER_NAME: 'Owner',
  BOOTSTRAP_OWNER_EMAIL: 'owner@boomburger.tm',
  BOOTSTRAP_OWNER_PHONE: '+99312555000',
  BOOTSTRAP_OWNER_PASSWORD: ownerPassword,
};

const added = [];
for (const [key, value] of Object.entries(defaults)) {
  if (!existing.has(key)) { existing.set(key, value); added.push(key); }
}

const order = Object.keys(defaults);
const body = [
  '# BOOM OS -- local configuration. Generated by scripts/setup-env.mjs.',
  '# Contains passwords: never commit this file (.gitignore already excludes it).',
  '',
  ...order.map(k => `${k}=${existing.get(k)}`),
  ...[...existing.keys()].filter(k => !order.includes(k)).map(k => `${k}=${existing.get(k)}`),
  '',
].join('\n');

fs.writeFileSync(ENV_PATH, body);

if (!added.length) {
  console.log('.env is already complete -- nothing changed.');
} else {
  console.log(fs.existsSync(ENV_PATH) && added.length === order.length
    ? '.env created.' : `.env updated: added ${added.join(', ')}.`);
}
console.log('');
console.log('  Sign in as:  ' + existing.get('BOOTSTRAP_OWNER_EMAIL'));
console.log('  Password:    ' + existing.get('BOOTSTRAP_OWNER_PASSWORD'));
console.log('');
console.log('  These credentials are stored in .env. The owner is created once, on an empty');
console.log('  database; changing the password here afterwards does not change the account.');
