import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const schema=read('prisma/schema.prisma');
const migration=read('prisma/migrations/20260908001000_inventory_recipes/migration.sql');
const route=read('server/routes/inventory.ts');
const payments=read('server/routes/payments.ts');
const server=read('server.ts');
const seed=read('server/seed.ts');
for(const model of ['InventoryItem','Recipe','RecipeIngredient','Supplier','Purchase','PurchaseItem','StockMovement']) if(!schema.includes(`model ${model}`)) throw new Error(`missing Prisma model ${model}`);
for(const table of ['inventory_items','recipes','recipe_ingredients','suppliers','purchases','purchase_items','stock_movements']) if(!migration.includes(`CREATE TABLE \"${table}\"`)) throw new Error(`missing migration table ${table}`);
for(const type of ['PURCHASE','SALE','WASTE','ADJUSTMENT','TRANSFER_IN','TRANSFER_OUT','RETURN']) if(!route.includes(`'${type}'`)) throw new Error(`missing movement type ${type}`);
for(const x of ['inventory.view','inventory.manage','inventory.purchase','inventory.access']) if(!seed.includes(`'${x}'`)) throw new Error(`missing permission ${x}`);
if(!server.includes("app.use('/api/inventory', inventoryRouter)")) throw new Error('inventory route not registered');
if(!payments.includes('consumeInventoryForOrder')) throw new Error('payment does not consume inventory');
if(!payments.includes("reference_type,reference_id,inventory_item_id,type") || !payments.includes('ON CONFLICT')) throw new Error('sale movement is not idempotent');
if(!route.includes('QUANTITY_MUST_BE_POSITIVE')) throw new Error('positive quantity validation missing');
if(!route.includes("current_stock<=reorder_point")) throw new Error('low stock rule missing');
if(!route.includes("type==='SALE'||type==='PURCHASE'")) throw new Error('manual sale/purchase movement protection missing');
console.log('Stage 14 inventory static acceptance: PASS');
